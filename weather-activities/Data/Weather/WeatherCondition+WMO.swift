import Foundation

nonisolated extension WeatherCondition {
    /// Groups a WMO weather interpretation code. Returns `nil` for codes Open-Meteo doesn't document.
    init?(wmoCode: Int) {
        switch wmoCode {
        case 0: self = .clear
        case 1, 2: self = .partlyCloudy
        case 3: self = .overcast
        case 45, 48: self = .fog
        case 51...57: self = .drizzle
        case 61...67, 80...82: self = .rain
        case 71...77, 85, 86: self = .snow
        case 95...99: self = .thunderstorm
        default: return nil
        }
    }
}
